#!/usr/bin/env python3
"""Draw the figures and write the result tables of SELAH's verification documentation from the report data.

Why this script exists: the verification pages show real results of the verification programs (src/tests/selah_vv_*
and the report-capable selah_test_* programs), not sketches. scripts/run_vv.sh runs them with SELAH_VV_DIR set; they
write their data there, and this script turns it into

* figures, docs/public/verification/<name>.png, each with its silver-ink twin <name>-dark.png drawn by the same code
  inside figure_theme.theme("dark") (the harness of the ADAM documentation, copied in docs/scripts/);
* result tables, docs/verification/_tables/<name>.md, included by the case pages (so the numbers on the pages are
  always those of the last report run).

A figure or table whose data is missing is skipped with a message.

Usage: make_doc_figures.py --data DIR [--out DIR] [--tables DIR] [--theme {light,dark,both}] [--only NAME ...]
Needs numpy and matplotlib.
"""

from __future__ import annotations

import argparse
import math
import re
import sys
from collections import defaultdict
from pathlib import Path

import matplotlib as mpl
import numpy as np

mpl.use('Agg')
sys.path.insert(0, str(Path(__file__).resolve().parent))
from selah_palette import STYLE as STYLE_LIGHT, STYLE_DARK, WASHI  # noqa: E402

mpl.rcParams['figure.facecolor'] = WASHI
mpl.rcParams['savefig.facecolor'] = WASHI
import matplotlib.pyplot as plt  # noqa: E402

from figure_theme import THEMES, theme, themes  # noqa: E402

DPI = 110
STYLE = dict(STYLE_LIGHT)  # swapped for STYLE_DARK while the dark twins are drawn (main)
RK = ['euler', 'ssp-22', 'ssp-33', 'ssp-54', 'ssp-104', 'rk4', 'lsrk-33', 'lsrk-54']
SPLIT = ['strang', 'yoshida-4', 'blanes-moan-s6', 'blanes-moan-s10']
ORDER = {'euler': 1, 'ssp-22': 2, 'ssp-33': 3, 'ssp-54': 4, 'ssp-104': 4, 'rk4': 4, 'lsrk-33': 3, 'lsrk-54': 4,
         'strang': 2, 'yoshida-4': 4, 'blanes-moan-s6': 4, 'blanes-moan-s10': 6}
FORM_LABEL = {'butcher': 'Butcher', 'butcher-q': 'Butcher, stages on q', 'two-reg': 'two-register',
              'shu-osher-2r': 'two-register', '2n': 'Williamson 2N', 'williamson-2n': 'Williamson 2N',
              'ket': 'Ketcheson', 'ketcheson-2r': 'Ketcheson'}


def ffloat(x: str) -> float:
    """A Fortran real: also the ES form without the E of a 3-digit exponent ('5.4+112')."""
    try:
        return float(x)
    except ValueError:
        return float(re.sub(r'(?<=[0-9.])([+-])(\d{3})$', r'E\1\2', x))


def style(s: str) -> tuple[str, str]:
    return STYLE.get(s, ('0.4', '.'))


def fmt(x: float) -> str:
    """A number for a table: 4 significant digits, scientific below 1e-3."""
    if not math.isfinite(x):
        return '—'
    return f'{x:.2e}' if (x != 0 and abs(x) < 1e-3) or abs(x) >= 1e4 else f'{x:.4g}'


def orders(steps: list[int], errs: list[float]) -> list[float]:
    return [math.log(errs[i] / errs[i + 1]) / math.log(steps[i + 1] / steps[i]) for i in range(len(errs) - 1)]


class Figures:
    def __init__(self, data: Path, out: Path, tables: Path) -> None:
        self.data, self.out, self.tables = data, out, tables
        self.out.mkdir(parents=True, exist_ok=True)
        self.tables.mkdir(parents=True, exist_ok=True)
        self.dark = False

    # ---------------------------------------------------------------------------------------------------------- io
    def has(self, *names: str) -> bool:
        missing = [n for n in names if not (self.data / n).exists()]
        if missing:
            print(f'  skipped: missing {", ".join(missing)}')
        return not missing

    def load(self, name: str) -> np.ndarray:
        return np.loadtxt(self.data / name, ndmin=2)

    def rows(self, name: str) -> list[list[str]]:
        return [ln.split() for ln in (self.data / name).read_text().splitlines() if ln and not ln.startswith('#')]

    def save(self, fig: plt.Figure, name: str) -> None:
        fig.savefig(self.out / f'{name}.png', dpi=DPI, bbox_inches='tight')
        plt.close(fig)

    def table(self, name: str, header: list[str], body: list[list[str]], note: str = '') -> None:
        if self.dark:
            return  # tables once, in the light pass
        lines = ['<!-- Generated by docs/scripts/make_doc_figures.py from the report data: do not edit. -->', '',
                 '| ' + ' | '.join(header) + ' |', '|' + '---|' * len(header)]
        lines += ['| ' + ' | '.join(r) + ' |' for r in body]
        if note:
            lines += ['', note]
        (self.tables / f'{name}.md').write_text('\n'.join(lines) + '\n')

    # -------------------------------------------------------------------------------------------- A1 conditions
    def order_conditions(self) -> None:
        if not self.has('order-conditions.dat'):
            return
        rows = self.rows('order-conditions.dat')
        ncond = {1: 1, 2: 2, 3: 4, 4: 8}
        names, at_p, above = [], [], []
        body = []
        for r in rows:
            name, p, res = r[0], int(r[1]), [float(x) for x in r[2:10]]
            names.append(name)
            at_p.append(max(res[:ncond[p]]))
            above.append(max(res[ncond[p]:ncond[p + 1]]) if p < 4 else float('nan'))
            body.append([f'`{name}`', str(p), fmt(at_p[-1]), fmt(above[-1]) if p < 4 else '—'])
        fig, ax = plt.subplots(figsize=(7.2, 3.2))
        x = np.arange(len(names))
        ax.bar(x - 0.2, np.maximum(at_p, 1e-34), 0.4, color=[style(n)[0] for n in names], label='conditions up to $p$')
        ab = [a if math.isfinite(a) else np.nan for a in above]
        ax.bar(x + 0.2, ab, 0.4, color='0.7', label='first failing condition, order $p+1$')
        ax.set_yscale('log')
        ax.axhline(64 * 2.22e-16, color='0.3', lw=0.8, ls='--')
        ax.text(len(names) - 0.5, 64 * 2.22e-16 * 2, '64 ε (the bound)', ha='right', fontsize=8, color='0.3')
        ax.set_xticks(x, names, rotation=20, fontsize=8)
        ax.set_ylabel('largest residual')
        ax.legend(fontsize=8, loc='upper center', bbox_to_anchor=(0.5, -0.22), ncol=2, frameon=False)
        ax.grid(axis='y', alpha=0.3)
        self.save(fig, 'order-conditions')
        self.table('order-conditions', ['Scheme', 'Order $p$', 'Largest residual, trees up to $p$',
                                        'Largest residual, trees of $p+1$'], body,
                   'Residuals in quadruple precision (R8P with nvfortran). Exact zero shows as 0.')

    # ------------------------------------------------------------------------------------------ A2/A3/A4 orders
    def _convergence(self, groups: dict[str, tuple[list[int], list[float]]], title: str, name: str,
                     xlabel: str = 'steps') -> None:
        fig, ax = plt.subplots(figsize=(6.4, 4.2))
        for key, (steps, errs) in groups.items():
            scheme = key.split(' ')[0]
            c, m = style(scheme)
            ax.loglog(steps, errs, m + '-', color=c, mfc='none', ms=5, lw=1.1, label=key)
        ax.set_xlabel(xlabel)
        ax.set_ylabel('error')
        ax.set_title(title, fontsize=10)
        ax.grid(alpha=0.3, which='both')
        ax.legend(fontsize=7, ncol=2)
        self.save(fig, name)

    def scalar_orders(self) -> None:
        if not self.has('scalar-orders.dat'):
            return
        body = []
        for problem, ptitle in ((1, "$y' = -y$"), (2, "$y' = -y^2$")):
            groups = {}
            for r in self.rows('scalar-orders.dat'):
                if int(r[1]) != problem:
                    continue
                steps = [int(r[2 + 2 * k]) for k in range(5)]
                errs = [ffloat(r[3 + 2 * k]) for k in range(5)]
                groups[r[0]] = (steps, errs)
                body.append([f'`{r[0]}`', ptitle, str(ORDER[r[0]])] + [f'{o:.3f}' for o in orders(steps, errs)])
            self._convergence(groups, f'every scheme on {ptitle}, error at $t = 1$', f'scalar-orders-{problem}')
        self.table('scalar-orders', ['Scheme', 'Problem', 'Declared', 'Observed 8→16', '16→32', '32→64', '64→128'],
                   body)

    def stepper_orders(self) -> None:
        if not self.has('stepper-orders.dat'):
            return
        groups, body = {}, []
        for r in self.rows('stepper-orders.dat'):
            steps = [int(r[2 + 2 * k]) for k in range(4)]
            errs = [ffloat(r[3 + 2 * k]) for k in range(4)]
            if r[1] == 'butcher':
                groups[r[0]] = (steps, errs)
            body.append([f'`{r[0]}`', FORM_LABEL.get(r[1], r[1]), str(ORDER[r[0]])] +
                        [f'{o:.3f}' for o in orders(steps, errs)] + [fmt(errs[-1])])
        self._convergence(groups, 'through the stepper (Butcher form): periodic advection, $t = 0.25$', 'stepper-orders')
        self.table('stepper-orders', ['Scheme', 'Form', 'Declared', 'Observed, 1st halving', '2nd', '3rd',
                                      'Finest error'], body)

    def splitting_orders(self) -> None:
        if not self.has('splitting-orders.dat'):
            return
        groups, body = {}, []
        for r in self.rows('splitting-orders.dat'):
            name, first, problem = r[0], int(r[1]), int(r[2])
            steps = [int(r[3 + 2 * k]) for k in range(4)]
            errs = [ffloat(r[4 + 2 * k]) for k in range(4)]
            if first == 1 and problem == 2:
                groups[name] = (steps, errs)
            body.append([f'`{name}`', 'oscillator' if problem == 1 else 'pendulum', str(first), str(ORDER[name])] +
                        [f'{o:.3f}' for o in orders(steps, errs)] + [fmt(errs[-1])])
        self._convergence(groups, 'splittings on the pendulum, error at $t = 1$', 'splitting-orders', 'steps per unit time')
        self.table('splitting-orders', ['Scheme', 'Problem', 'First partition', 'Declared', 'Observed, 1st halving',
                                        '2nd', '3rd', 'Finest error'], body)

    # ---------------------------------------------------------------------------------------------- A5 stability
    def stability(self) -> None:
        if not self.has('stability-summary.dat'):
            return
        rows = self.rows('stability-summary.dat')
        fig, axs = plt.subplots(1, 2, figsize=(11, 4.4))
        panels = (('SSP schemes', ['euler', 'ssp-22', 'ssp-33', 'ssp-54', 'ssp-104']),
                  ('rk4 and the 2N schemes', ['rk4', 'lsrk-33', 'lsrk-54']))
        for ax, (title, names) in zip(axs, panels):
            for n in names:
                if not self.has(f'stability-{n}.dat'):
                    continue
                d = self.load(f'stability-{n}.dat')
                x = d[:241, 0]
                y = d[::241, 1]
                z = d[:, 2].reshape(241, 241)
                c, _ = style(n)
                ax.contour(x, y, z, levels=[1.0], colors=[c], linewidths=1.3)
                ax.plot([], [], color=c, label=n)
            ax.axhline(0, color='0.5', lw=0.6)
            ax.axvline(0, color='0.5', lw=0.6)
            ax.set_aspect('equal')
            ax.set_xlabel('Re $z$')
            ax.set_ylabel('Im $z$')
            ax.set_title(title + ': $|R(z)| = 1$', fontsize=10)
            ax.legend(fontsize=8, loc='upper left')
            ax.grid(alpha=0.25)
        axs[0].set_xlim(-16, 2)
        axs[0].set_ylim(-11, 11)
        axs[1].set_xlim(-5.5, 1.5)
        axs[1].set_ylim(-4, 4)
        self.save(fig, 'stability')
        body = []
        for r in rows:
            c = ffloat(r[5])
            body.append([f'`{r[0]}`', r[1], r[2], f'{ffloat(r[3]):.6f}', f'{ffloat(r[4]):.6f}',
                         f'{c:.4f}' if c > 0 else '—', f'{-ffloat(r[3]) / int(r[1]):.4f}'])
        self.table('stability', ['Scheme', 'Stages', 'Order', 'Real-axis limit', 'Imaginary-axis limit',
                                 'SSP coefficient $C$', 'Real limit / stages'], body)

    # --------------------------------------------------------------------------------------------------- P1 TVD
    def ssp_tvd(self) -> None:
        if not self.has('ssp-tvd-sweep.dat', 'ssp-tvd-summary.dat'):
            return
        data = defaultdict(list)
        for r in self.rows('ssp-tvd-sweep.dat'):
            data[r[0]].append((ffloat(r[1]), ffloat(r[2])))
        fig, axs = plt.subplots(1, 2, figsize=(11, 3.8))
        for ax, names, xl in ((axs[0], ['euler', 'ssp-22', 'ssp-33', 'ssp-54', 'ssp-104'], r'$\nu / C$'),
                              (axs[1], ['rk4', 'lsrk-33', 'lsrk-54'], r'$\nu$ (forward-Euler limit 1)')):
            for n in names:
                pts = np.array(data[n])
                c, m = style(n)
                ax.semilogy(pts[:, 0], np.maximum(pts[:, 1], 1e-17), m + '-', color=c, mfc='none', ms=4, lw=1.0,
                            label=n)
            ax.axvline(1.0, color='0.3', lw=0.8, ls='--')
            ax.set_xlabel(xl)
            ax.set_ylabel('largest one-step TV growth / TV$_0$')
            ax.set_ylim(1e-17, 2)
            ax.grid(alpha=0.3)
            ax.legend(fontsize=8)
        axs[0].set_title('SSP schemes: TVD up to $\\nu = C$ (the dashed line), as proven', fontsize=10)
        axs[1].set_title('not SSP: no guarantee', fontsize=10)
        self.save(fig, 'ssp-tvd')
        body = []
        for r in self.rows('ssp-tvd-summary.dat'):
            c, t = ffloat(r[1]), ffloat(r[2])
            body.append([f'`{r[0]}`', f'{c:.4f}' if c > 0 else '— (not SSP)', f'{t:.3f}',
                         f'{t / c:.3f}' if c > 0 else '—'])
        self.table('ssp-tvd', ['Scheme', 'SSP coefficient $C$', 'TV first grows at $\\nu$', 'that $\\nu / C$'], body,
                   'Sweep step 0.05 C (0.05 for the schemes that are not SSP): a threshold is the first swept '
                   '$\\nu$ at which the total variation grew by more than 1000 ε.')

    # ------------------------------------------------------------------------------------------ P3 energy
    def splitting_energy(self) -> None:
        names = ['strang', 'yoshida-4', 'blanes-moan-s6', 'rk4', 'ssp-54']
        if not self.has(*[f'splitting-energy-{n}.dat' for n in names]):
            return
        fig, ax = plt.subplots(figsize=(7.2, 3.8))
        body = []
        for n in names:
            d = self.load(f'splitting-energy-{n}.dat')
            c, m = style(n)
            ax.semilogy(d[:, 0], np.maximum(d[:, 1], 1e-18), '-', color=c, lw=0.9, label=n)
            k = len(d) // 10
            first, last = d[:k, 1].max(), d[-k:, 1].max()
            body.append([f'`{n}`', 'splitting' if n in SPLIT else 'Runge–Kutta', fmt(first), fmt(last),
                         f'{last / first:.2f}'])
        ax.set_xlabel('$t$ (1000 periods, $\\Delta t = 0.1$)')
        ax.set_ylabel('largest $|H - H_0|$ per window')
        ax.set_title('harmonic oscillator: energy error', fontsize=10)
        ax.grid(alpha=0.3)
        ax.legend(fontsize=8, ncol=2)
        self.save(fig, 'splitting-energy')
        self.table('splitting-energy', ['Scheme', 'Kind', 'Max $|H-H_0|$, first tenth', 'Last tenth', 'Ratio'], body,
                   'Every step counted: the figure and the table plot the largest error in each of 400 windows of '
                   'the run (point samples would alias the fast oscillation of a splitting\'s energy error).')

    # --------------------------------------------------------------------------------------- P4 telescoping
    def telescoping(self) -> None:
        if not self.has('telescoping.dat'):
            return
        worst = defaultdict(lambda: [0.0, 0.0])
        for r in self.rows('telescoping.dat'):
            k = (r[0], r[1])
            worst[k][0] = max(worst[k][0], ffloat(r[3]))
            worst[k][1] = max(worst[k][1], ffloat(r[4]))
        keys = list(worst)
        fig, ax = plt.subplots(figsize=(8.5, 3.4))
        x = np.arange(len(keys))
        ax.bar(x - 0.2, [max(worst[k][0], 1e-18) for k in keys], 0.4, color=[style(k[0])[0] for k in keys],
               label='weights stage_weight(k)')
        ax.bar(x + 0.2, [max(worst[k][1], 1e-18) for k in keys], 0.4, color='0.7', label='uniform weights 1/s')
        ax.set_yscale('log')
        ax.set_xticks(x, [f'{k[0]}\n{FORM_LABEL.get(k[1], k[1])}' for k in keys], fontsize=6.5, rotation=60)
        ax.set_ylabel('$|\\Delta m + \\Delta t \\sum_k w_k F_k|$')
        ax.legend(fontsize=8)
        ax.grid(axis='y', alpha=0.3)
        self.save(fig, 'telescoping')
        self.table('telescoping', ['Scheme', 'Form', 'Defect with stage_weight', 'Defect with uniform weights'],
                   [[f'`{k[0]}`', FORM_LABEL.get(k[1], k[1]), fmt(worst[k][0]), fmt(worst[k][1])] for k in keys],
                   'Largest over 4 steps of inflow/outflow advection. The weights of euler, ssp-22 and ssp-104 '
                   '(Ketcheson\'s $b_k = 1/10$) are uniform: for them the two columns agree, as they must.')

    # --------------------------------------------------------------------------------------------- C2 forms
    def forms(self) -> None:
        if not self.has('forms.dat'):
            return
        data = defaultdict(list)
        for r in self.rows('forms.dat'):
            data[(r[0], r[1])].append((int(r[2]), ffloat(r[3])))
        fig, ax = plt.subplots(figsize=(6.4, 3.6))
        body = []
        for (s, f), pts in data.items():
            p = np.array(pts)
            c, m = style(s)
            ax.semilogy(p[:, 0], np.maximum(p[:, 1], 1e-18), m + '-', color=c, mfc='none', ms=3, lw=0.9,
                        label=f'{s}, {FORM_LABEL.get(f, f)}')
            body.append([f'`{s}`', FORM_LABEL.get(f, f), fmt(p[:, 1].max())])
        ax.axhline(1000 * 2.22e-16, color='0.3', lw=0.8, ls='--')
        ax.set_xlabel('step')
        ax.set_ylabel('max $|q_{form} - q_{Butcher}|$ / max $|q|$')
        ax.grid(alpha=0.3)
        ax.legend(fontsize=7)
        self.save(fig, 'forms')
        self.table('forms', ['Scheme', 'Form', 'Largest relative difference from the Butcher form, 40 steps'], body,
                   'Bound asserted: 1000 ε (the dashed line). A zero difference shows as 0.')


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--data', type=Path, required=True)
    ap.add_argument('--out', type=Path, default=Path('docs/public/verification'))
    ap.add_argument('--tables', type=Path, default=Path('docs/verification/_tables'))
    ap.add_argument('--theme', choices=THEMES, default='both')
    ap.add_argument('--only', nargs='*')
    args = ap.parse_args()
    f = Figures(args.data, args.out, args.tables)
    jobs = {
        'order-conditions': f.order_conditions,
        'scalar-orders': f.scalar_orders,
        'stepper-orders': f.stepper_orders,
        'splitting-orders': f.splitting_orders,
        'stability': f.stability,
        'ssp-tvd': f.ssp_tvd,
        'splitting-energy': f.splitting_energy,
        'telescoping': f.telescoping,
        'forms': f.forms,
    }
    for th in themes(args.theme):
        f.dark = th == 'dark'
        STYLE.clear()
        STYLE.update(STYLE_DARK if f.dark else STYLE_LIGHT)
        with theme(th):
            for name, job in jobs.items():
                if args.only and name not in args.only:
                    continue
                print(f'{name} ({th})')
                job()
    return 0


if __name__ == '__main__':
    sys.exit(main())
